from odoo.exceptions import AccessError, MissingError, ValidationError
from odoo.http import request, route

from odoo.addons.website_sale.controllers.reorder import CustomerPortal


class ReorderWithItsSpecifications(CustomerPortal):
    """Reordering has to bring back what was configured, not just the products.

    ODOO REORDERS BY PRODUCT. It walks the lines and adds each product to the
    cart as if somebody had clicked it in the shop, which is right for a
    catalogue item and wrong for everything this shop configures:

      a custom spring   is one product carrying a specification and a price
                        worked out from cone, steel, labour and markup. Added
                        as a product it comes back at its catalogue price,
                        which is deliberately 0.00, with no wire, no length and
                        no door - the floor would be handed a spring nobody
                        can wind and the customer would pay nothing for it.
      a kit             carries the door it was sized for in the same way.
      a prepared track  brings its own jamb brackets and flag angle, which the
                        cart adds by itself. Copying the ones already on the
                        order would ship two sets.

    So the lines are sorted into three kinds and each is treated as what it
    is: configured lines are COPIED with their specification and their price,
    preparation parts are left to be regenerated, and everything else is added
    the ordinary way, at today's price.

    THE COPIED PRICE IS THE OLD ONE, which is worth saying plainly. A spring
    quoted at $342 last month comes back at $342: the specification is stored
    as text, not as the numbers the calculator priced, so there is nothing here
    to recompute from. Repeating a known order at a known price is the
    behaviour a customer expects, and it beats the alternative by a distance -
    but if the steel rate moves, a reordered spring carries the old one.
    """

    # What the line copier brings across, beyond the product and the quantity.
    SPEC_FIELDS = (
        "aa_spec_note", "aa_door_width_in", "aa_door_height_in",
        "aa_door_weight_lb", "aa_door_hi_lift_in", "aa_door_cycles",
    )

    def _aa_is_configured(self, line):
        """A line whose price and description were worked out, not looked up."""
        if "aa_spec_note" not in line._fields:
            return False

        configured = line.order_id._door_configured_price_products()

        return line.product_id in configured or bool(line.aa_spec_note)

    @route()
    def my_orders_reorder(self, order_id, access_token=None):
        try:
            order_sudo = self._document_check_access(
                "sale.order", order_id, access_token=access_token)
        except (AccessError, MissingError):
            return request.redirect("/my")

        lines = order_sudo.order_line.filtered(
            lambda line: line.with_user(request.env.user).sudo()
            ._is_reorder_allowed()
        )

        if not lines:
            raise ValidationError(
                request.env._("Nothing can be reordered in this order"))

        # A preparation part is regenerated by the cart when its track goes in,
        # so carrying the old one over would double it.
        if "track_prep_parent_id" in lines._fields:
            lines = lines.filtered(lambda line: not line.track_prep_parent_id)

        cart_sudo = request.cart or request.website._create_cart()

        # REORDERING REPLACES THE CART, which the owner asked for and which is
        # the honest reading of the button: it says order THIS again, not add
        # this to whatever is already here. The panel says so above the list,
        # because a customer who has spent ten minutes filling a cart should
        # not discover this by losing it.
        cart_sudo.order_line.unlink()
        # Which new line each old one became, so a spring linked to its kit
        # comes back linked to the kit it arrived with.
        made = {}

        for line in lines:
            if self._aa_is_configured(line):
                made[line.id] = self._aa_copy_configured(cart_sudo, line, made)
                continue

            values = cart_sudo._cart_add(
                product_id=line.product_id.id,
                quantity=line.product_uom_qty,
                no_variant_attribute_value_ids=(
                    line.product_no_variant_attribute_value_ids.ids),
                linked_line_id=made.get(line.linked_line_id.id, False),
            )
            new_line = request.env["sale.order.line"].sudo().browse(
                values.get("line_id")).exists()

            if new_line:
                made[line.id] = new_line.id
                # THE DOOR TRAVELS WITH THE KIT. It is stored on the line, and
                # adding the product again would otherwise lose the one thing
                # the work order sheet needs.
                self._aa_carry_specification(line, new_line)

        return {
            "cart_quantity": cart_sudo.cart_quantity,
            "tracking_info": [],
        }

    def _aa_copy_configured(self, cart_sudo, line, made):
        """Put a configured line back exactly as it was, price included."""
        values = {
            "order_id": cart_sudo.id,
            "product_id": line.product_id.id,
            "product_uom_qty": line.product_uom_qty,
            "name": line.name,
            "price_unit": line.price_unit,
            "discount": line.discount,
            "linked_line_id": made.get(line.linked_line_id.id, False),
        }

        for field in self.SPEC_FIELDS:
            if field in line._fields:
                values[field] = line[field]

        new_line = request.env["sale.order.line"].sudo().create(values)
        # price_unit is computed from the product and the pricelist on create,
        # and these products deliberately list at zero, so it is written after
        # - the same order add_assembly_lines does it in, for the same reason.
        new_line.write({"price_unit": line.price_unit})

        return new_line.id

    def _aa_carry_specification(self, line, new_line):
        values = {
            field: line[field]
            for field in self.SPEC_FIELDS
            if field in line._fields and line[field]
        }

        if values:
            new_line.sudo().write(values)
