#!/usr/bin/env python3
"""ASSEMBLE THE ONE BLOCK THAT GOES INTO WORDPRESS.

The viewer is three files here - a stylesheet, a script and a texture - which
is the right shape for a repository and the wrong shape for somebody pasting
into a page. So this flattens the first two into a single snippet he can
select, copy and paste into a Custom HTML block, with nothing to upload but
the texture.

GENERATED, NEVER EDITED. Editing the snippet by hand is how it comes to differ
from the viewer it was made from, and then a bug fixed here stays live on the
website. Run this instead:

    python3 aa_door_preview/tools/build_embed.py

It writes static/src/wordpress_embed.txt - .txt, not .html, so that opening it
in a browser shows the text to copy instead of running it.

NO <script src> TAGS IN THE SNIPPET. The site is Elementor, and an Elementor
HTML widget has its markup INJECTED into the page rather than parsed with it -
and setting innerHTML never executes an external script. So the two library
tags this block used to carry simply did not run, and the viewer reported that
it could not load its renderer (owner, 2026-10-26). The viewer now appends
those scripts itself, which does execute them, whoever injected the markup.

WHY THE LIBRARIES STILL COME FROM A CDN. Everything else is inline, and
three.js could be too, but it is 600 KB and a 600 KB block is a page editor's
idea of a bad afternoon. It could equally be uploaded alongside the texture -
except that Sirv is a media service and whether it returns
application/javascript for a .js file is not something worth finding out on a
live product page. An image it will certainly serve correctly. So: scripts
from jsDelivr, pinned to an exact version, and the texture next to his models.
"""

import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), "static", "src")

THREE_VERSION = "0.137.5"
THREE_CDN = "https://cdn.jsdelivr.net/npm/three@%s/build/three.min.js" % THREE_VERSION
LOADER_CDN = ("https://cdn.jsdelivr.net/npm/three@%s/examples/js/loaders/"
              "GLTFLoader.js" % THREE_VERSION)

MODEL_URL = "https://davidaaigd.sirv.com/3d/White_Clear.glb"
WOOD_URL = "https://davidaaigd.sirv.com/3d/woodgrain.jpg"

FONTS = ("https://fonts.googleapis.com/css2?family=Archivo:wght@400;500;600"
         "&family=Archivo+Narrow:wght@500;600"
         "&family=IBM+Plex+Mono:wght@400;500&display=swap")

TEMPLATE = """<!-- =====================================================================
     SERIES 1200 DOOR PREVIEW            build %(stamp)s
     Paste this whole block into the Elementor HTML widget on the product
     page, in place of the current viewer.

     Before it will work, one file has to be uploaded:
         woodgrain.jpg  ->  %(wood)s
     Nothing else needs uploading. If that file is missing everything still
     works; the Wood finish just comes out plain brown instead of grained.

     Generated by aa_door_preview/tools/build_embed.py - do not edit here,
     edit the module and run that again.
     ================================================================== -->

<link rel="stylesheet" href="%(fonts)s">

<style>
%(css)s
</style>

<div data-aa-door-preview
     data-model="%(model)s"
     data-wood="%(wood)s"
     data-three="%(three)s"
     data-gltf-loader="%(loader)s"></div>

<script>
%(js)s

/* WHICH BUILD THIS IS. A browser caches a .txt as happily as anything else,
 * and a stale copy of this block looks exactly like a fix that did not work -
 * which cost a round trip on 2026-10-26. The test pages print this, so an old
 * copy announces itself instead of being guessed at. */
if (window.AADoorPreview) { window.AADoorPreview.built = "%(stamp)s"; }
</script>
"""


