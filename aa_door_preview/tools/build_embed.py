def read(name):
    with open(os.path.join(SRC, name), "r", encoding="utf-8") as fh:
        return fh.read().strip()


def main():
    css = read("door_preview.css")
    js = read("door_preview.js")

    # A closing script tag anywhere in the script text would end the block
    # early and spill the rest of the viewer onto the page as words.
    for name, body in (("css", css), ("js", js)):
        if re.search(r"</\s*script", body, re.I):
            sys.exit("%s contains a closing script tag; it cannot be inlined"
                     % name)
    if re.search(r"</\s*style", css, re.I):
        sys.exit("the stylesheet contains a closing style tag")

    # THE BUILD ID IS A HASH OF EVERYTHING THE BLOCK CARRIES, not a clock. A
    # timestamp would make every run a change in the repository even when
    # nothing moved; a hash identifies the build and stays put until the block
    # actually differs.
    #
    # THE URLS ARE IN IT. They were not at first, and so moving the model and
    # texture off Sirv produced a materially different block under the same
    # id - from the one safeguard whose whole job is to tell two versions
    # apart.
    stamp = hashlib.sha256("\n".join([
        css, js, MODEL_URL, WOOD_URL, THREE_CDN, LOADER_CDN,
    ]).encode("utf-8")).hexdigest()[:8]

    out = TEMPLATE % {
        "css": css, "js": js, "fonts": FONTS, "three": THREE_CDN,
        "loader": LOADER_CDN, "model": MODEL_URL, "wood": WOOD_URL,
        "stamp": stamp,
    }

    path = os.path.join(SRC, "wordpress_embed.txt")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(out)

    print("wrote %s (%.1f KB, build %s)"
          % (path, len(out.encode("utf-8")) / 1024.0, stamp))

    # AND A PAGE THAT IS NOTHING BUT THAT SNIPPET, so the thing he is about to
    # paste can be looked at working before it goes anywhere near a product
    # page - pointed at this module's own copies of the model and texture,
    # since the live site's paths mean nothing here.
    local = out.replace(MODEL_URL, TEST_MODEL_URL).replace(WOOD_URL,
                                                           TEST_WOOD_URL)
    page = ("<!doctype html>\n<html lang=\"en\">\n<head>\n"
            "<meta charset=\"utf-8\">\n"
            "<meta name=\"viewport\" content=\"width=device-width,"
            " initial-scale=1\">\n"
            "<title>Series 1200 embed test</title>\n"
            "<style>body{margin:0;background:#0c0f12}</style>\n"
            "</head>\n<body>\n\n" + local + "\n</body>\n</html>\n")

    path = os.path.join(SRC, "embed_test.html")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(page)

    print("wrote %s" % path)

    # AND A PAGE THAT INJECTS THE SNIPPET THE WAY ELEMENTOR DOES, because
    # that is the way it failed. An Elementor HTML widget does not have its
    # markup parsed with the page; it is set as innerHTML, which runs no
    # scripts at all, and then the scripts are picked back out and re-run.
    # Pasting into the editor to find out is a slow way to test it.
    # The injection test fetches a block, and on this origin it has to be the
    # one pointed at the local copies.
    path = os.path.join(SRC, "embed_local.txt")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(local)

    print("wrote %s" % path)

    path = os.path.join(SRC, "elementor_test.html")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(ELEMENTOR_TEST)

    print("wrote %s" % path)

    # AND THE HAND-WRITTEN TEST PAGE GETS THE BUILD ID TOO.
    #
    # It loads door_preview.js directly rather than through the block, so
    # nothing in it said which version was running - and a browser holding
    # yesterday's script made a fix that worked look like a fix that did
    # not, twice in one day (2026-10-26 and again on the 27th). The query
    # string changes whenever the file does, so the browser has to fetch it,
    # and the id is printed at the top where it can be read off a screenshot.
    path = os.path.join(SRC, "preview.html")

    with open(path, "r", encoding="utf-8") as fh:
        page = fh.read()

    page = re.sub(r'(href="\./door_preview\.css)(\?v=[0-9a-f]+)?"',
                  r'\1?v=%s"' % stamp, page)
    page = re.sub(r'(src="\./door_preview\.js)(\?v=[0-9a-f]+)?"',
                  r'\1?v=%s"' % stamp, page)
    page = re.sub(r'<p class="stamp">.*?</p>',
                  '<p class="stamp">Build %s &middot; test page</p>' % stamp,
                  page, flags=re.S)

    with open(path, "w", encoding="utf-8") as fh:
        fh.write(page)

    print("stamped %s" % path)

    # AND THE PAGE HE ACTUALLY USES: one button that puts the whole block on
    # the clipboard. Selecting 30 KB of text by hand and missing the last
    # line is a failure that looks like a bug in the viewer.
    path = os.path.join(SRC, "copy.html")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(COPY_PAGE)

    print("wrote %s" % path)


if __name__ == "__main__":
    main()
