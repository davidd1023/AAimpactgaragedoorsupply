#!/usr/bin/env python3
"""ASSEMBLE THE ONE BLOCK THAT GOES INTO WORDPRESS.

The viewer is three files here - a stylesheet, a script and a texture - which
is the right shape for a repository and the wrong shape for somebody pasting
into a page. So this flattens the first two into a single snippet he can
select, copy and paste into a Custom HTML block, with nothing to upload but
the texture.

GENERATED, NEVER EDITED. Editing the snippet by hand is how it comes to differ
from the viewer it was made from, and then a bug fixed here stays live on the
website. Run this instead:

    python3 aa_door_preview/tools/build_embed.py

It writes static/src/wordpress_embed.txt - .txt, not .html, so that opening it
in a browser shows the text to copy instead of running it.

WHY THE TWO LIBRARY FILES STILL COME FROM A CDN. Everything else is inline,
and three.js could be too, but it is 600 KB and a 600 KB block is a page
editor's idea of a bad afternoon. It could equally be uploaded alongside the
texture - except that Sirv is a media service and whether it returns
application/javascript for a .js file is not something worth finding out on a
live product page. An image it will certainly serve correctly. So: scripts
from jsDelivr, pinned to an exact version, and the texture next to his models.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), "static", "src")

THREE_VERSION = "0.137.5"
THREE_CDN = "https://cdn.jsdelivr.net/npm/three@%s/build/three.min.js" % THREE_VERSION
LOADER_CDN = ("https://cdn.jsdelivr.net/npm/three@%s/examples/js/loaders/"
              "GLTFLoader.js" % THREE_VERSION)

MODEL_URL = "https://davidaaigd.sirv.com/3d/White_Clear.glb"
WOOD_URL = "https://davidaaigd.sirv.com/3d/woodgrain.jpg"

FONTS = ("https://fonts.googleapis.com/css2?family=Archivo:wght@400;500;600"
         "&family=Archivo+Narrow:wght@500;600"
         "&family=IBM+Plex+Mono:wght@400;500&display=swap")

TEMPLATE = """<!-- =====================================================================
     SERIES 1200 DOOR PREVIEW
     Paste this whole block into a Custom HTML block on the product page,
     in place of the current viewer.

     Before it will work, one file has to be uploaded:
         woodgrain.jpg  ->  %(wood)s
     Nothing else needs uploading. If that file is missing everything still
     works; the Wood finish just comes out plain brown instead of grained.

     Generated by aa_door_preview/tools/build_embed.py - do not edit here,
     edit the module and run that again.
     ================================================================== -->

<link rel="stylesheet" href="%(fonts)s">

<style>
%(css)s
</style>

<div data-aa-door-preview
     data-model="%(model)s"
     data-wood="%(wood)s"></div>

<script src="%(three)s"></script>
<script src="%(loader)s"></script>
<script>
%(js)s
</script>
"""


def read(name):
    with open(os.path.join(SRC, name), "r", encoding="utf-8") as fh:
        return fh.read().strip()


def main():
    css = read("door_preview.css")
    js = read("door_preview.js")

    # A closing script tag anywhere in the script text would end the block
    # early and spill the rest of the viewer onto the page as words.
    for name, body in (("css", css), ("js", js)):
        if re.search(r"</\s*script", body, re.I):
            sys.exit("%s contains a closing script tag; it cannot be inlined"
                     % name)
    if re.search(r"</\s*style", css, re.I):
        sys.exit("the stylesheet contains a closing style tag")

    out = TEMPLATE % {
        "css": css, "js": js, "fonts": FONTS, "three": THREE_CDN,
        "loader": LOADER_CDN, "model": MODEL_URL, "wood": WOOD_URL,
    }

    path = os.path.join(SRC, "wordpress_embed.txt")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(out)

    print("wrote %s (%.1f KB)" % (path, len(out.encode("utf-8")) / 1024.0))

    # AND A PAGE THAT IS NOTHING BUT THAT SNIPPET, so the thing he is about to
    # paste can be looked at working - over the real CDN, with the real
    # texture URL - before it goes anywhere near a product page.
    page = ("<!doctype html>\n<html lang=\"en\">\n<head>\n"
            "<meta charset=\"utf-8\">\n"
            "<meta name=\"viewport\" content=\"width=device-width,"
            " initial-scale=1\">\n"
            "<title>Series 1200 embed test</title>\n"
            "<style>body{margin:0;background:#0c0f12}</style>\n"
            "</head>\n<body>\n\n" + out + "\n</body>\n</html>\n")

    path = os.path.join(SRC, "embed_test.html")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(page)

    print("wrote %s" % path)


if __name__ == "__main__":
    main()
